/**
 * Runs after `next build`. Derives two Cloudflare files from the real export,
 * so they always match the pages that exist:
 *
 *   out/_redirects  the hand-written rules from public/_redirects, plus a 301
 *                   from the slashless form of every page to its canonical
 *                   trailing-slash URL (the asset server would answer 307).
 *   out/_headers    the hand-written rules from public/_headers, plus
 *                   X-Robots-Tag: noindex on every RSC payload (index.txt).
 */
import { readdirSync, readFileSync, statSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const OUT = "out";

function pages(dir = OUT, base = "") {
  const found = [];
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (!statSync(full).isDirectory() || name.startsWith("_next")) continue;
    const path = `${base}/${name}`;
    if (existsSync(join(full, "index.html"))) found.push(`${path}/`);
    found.push(...pages(full, path));
  }
  return found;
}

// The not-found page is served by the asset server's 404 handling, not linked.
const all = pages()
  .filter((p) => p !== "/404/")
  .sort();
const stamp = "# Generated by scripts/postbuild.mjs from the build output. Do not edit here.";

const redirects = readFileSync("public/_redirects", "utf8").trimEnd();
const slashless = all.map((p) => `${p.slice(0, -1)}  ${p}  301`);
writeFileSync(join(OUT, "_redirects"), `${redirects}\n\n${stamp}\n${slashless.join("\n")}\n`);

const headers = readFileSync("public/_headers", "utf8").trimEnd();
const rsc = ["/", ...all].map((p) => `${p}index.txt\n  X-Robots-Tag: noindex`);
writeFileSync(join(OUT, "_headers"), `${headers}\n\n${stamp}\n${rsc.join("\n")}\n`);

const rules = headers.split("\n").filter((l) => l && !l.startsWith(" ") && !l.startsWith("#")).length + rsc.length;
if (rules > 100) throw new Error(`_headers has ${rules} rules; Cloudflare allows 100.`);
console.log(`postbuild: ${slashless.length} slashless redirects, ${rsc.length} RSC noindex rules`);
